const assert=require('node:assert/strict');
const parser=require('../parser.js');
const {TreeModel}=require('../tree-model.js');
let m=new TreeModel(parser.detect('{"a":[1,{"b":"value"}],"empty":{},"a":9007199254740993}'));
m.configure({action:'expand'});
assert.equal(m.totalLines,parser.serialize(m.result,2).split('\n').length);
assert.deepEqual(m.viewport(0,100).rows.map(r=>r.line),Array.from({length:m.totalLines},(_,i)=>i+1));
const target=m.nodes.find(n=>n.label==='"b"');const stableLine=target.start;
m.configure({action:'collapse'});assert.equal(m.rows.length,1);
m.configure({query:'value'});assert.equal(m.matches,1);assert(m.viewport(0,100).rows.some(r=>r.line===stableLine));
m.configure({query:'',action:'expand'});assert.equal(m.nodes[target.id].start,stableLine);
assert(parser.serialize(m.result).includes('9007199254740993'));
console.log('PASS line coordinates, folding, filtering and lossless values');
m=new TreeModel(parser.detect('42\n{"a":[]}\nnull'));
assert.equal(m.result.format,'JSONL');assert.equal(m.roots.length,3);assert.equal(m.totalLines,5);
console.log('PASS JSONL scalar and empty-container records');
const text='x'.repeat(11*1024*1024)+'TAIL';
m=new TreeModel(parser.detect(JSON.stringify({text})),{columns:90});
let view=m.viewport(m.visualLines-8,8);assert(view.rows.length<=8);assert(view.rows.some(r=>r.tokens.some(t=>t.text.includes('TAIL'))));assert(JSON.stringify(view).length<20000);
m.configure({wrap:false});view=m.viewport(0,10,text.length-40);assert(JSON.stringify(view).length<20000);assert(view.rows.some(r=>r.tokens.some(t=>t.text.includes('TAIL'))));
console.log('PASS huge single values are clipped in both wrapped and horizontal views');
m=new TreeModel(parser.detect(JSON.stringify(Array.from({length:20000},(_,id)=>({id,label:'record '+id})))));
m.configure({action:'expand'});assert(m.visualLines>50000);view=m.viewport(m.visualLines-30,30);assert(view.rows.length<=30);assert(view.rows.some(r=>r.tokens.some(t=>t.text.includes('19999'))));
assert(view.parents.length<=4);
console.log('PASS large tree mounts a bounded window including its last record');
