const assert=require('node:assert/strict');
const parser=require('../parser.js');
const {TreeModel}=require('../tree-model.js');
const text=JSON.stringify({needle:'needle needle',nested:{message:'before '+ 'padding '.repeat(100)+'needle after'},other:'none'});
const model=new TreeModel(parser.detect(text),{columns:40});
let meta=model.configure({query:'needle'});
assert.equal(meta.matches,4);assert.equal(meta.navigation.index,0);
let hit=model.navigate(1);assert.equal(hit.index,1);
assert.equal(model.navigate(1).index,2);const far=model.navigate(1);assert.equal(far.index,3);assert(far.target.visual>10);
assert.equal(model.navigate(1).index,0);assert.equal(model.navigate(-1).index,3);
let view=model.viewport(Math.max(0,far.target.visual-3),10);
assert(view.rows.some(r=>r.tokens.some(t=>t.matches.some(m=>m.active))));
assert.equal(parser.serialize(model.result),parser.serialize(parser.detect(text)));
model.configure({wrap:false});hit=model.navigation();assert.equal(hit.index,3);assert(hit.target.column>500);
view=model.viewport(hit.target.visual,2,hit.target.column);
assert(view.rows.some(r=>r.tokens.some(t=>t.matches.some(m=>m.active))));
assert.equal(model.configure({query:'absent'}).navigation.total,0);assert.equal(model.navigate(1).index,-1);
assert.equal(model.configure({query:''}).matches,0);
console.log('PASS individual occurrences, same-value repeats, cyclic navigation, wrapped and horizontal far matches');
const md=new TreeModel(parser.detect(JSON.stringify({message:'**nee**dle and needle\nneedle'})),{markdown:true,columns:12});
assert.equal(md.configure({query:'needle'}).matches,3);
const first=md.viewport(0,20);assert(first.rows.some(r=>r.tokens.filter(t=>t.matches.some(m=>m.active)).length===2));
const last=md.navigate(-1);assert.equal(last.index,2);
assert(md.viewport(last.target.visual,2).rows.some(r=>r.tokens.some(t=>t.matches.some(m=>m.active))));
console.log('PASS Markdown matches across styled tokens and decoded newlines');
const jsonl=new TreeModel(parser.detect('{"key":"needle"}\n{"key":"needle needle"}'));
assert.equal(jsonl.configure({query:'needle'}).matches,3);assert.equal(jsonl.navigate(-1).index,2);
console.log('PASS navigation across JSONL records');

const full=new TreeModel(parser.detect(JSON.stringify({before:'context before',branch:{deep:{message:'needle'},sibling:'nearby context'},unrelated:{child:'still visible'},after:'context after'})),{columns:100});
full.configure({action:'expand'});
const originalLines=full.rows.map(r=>full.describe(r).line);
full.configure({query:'needle'});
assert.deepEqual(full.rows.map(r=>full.describe(r).line),originalLines,'search must preserve every expanded row');
assert(full.rows.some(r=>full.tokens(full.nodes[r.id],r.close).some(t=>t.text.includes('still visible'))));
assert.equal(full.navigation().total,1);
full.configure({query:'absent'});
assert.deepEqual(full.rows.map(r=>full.describe(r).line),originalLines,'zero matches must not hide the tree');
full.configure({query:'',action:'collapse'});
full.configure({query:'needle'});
const rendered=full.viewport(0,100).rows;
for(const value of ['context before','nearby context','context after','needle'])assert(rendered.some(r=>r.tokens.some(t=>t.text.includes(value))),value+' remains visible');
const unrelated=full.nodes.find(n=>n.label==='"unrelated"');
assert(rendered.some(r=>r.id===unrelated.id),'unrelated folded branch remains in the tree');
assert.equal(full.isOpen(unrelated),false,'unrelated folded branch keeps its fold state');
full.configure({query:''});
assert.equal(full.rows.length,1,'clearing search restores original folding');
console.log('PASS full-tree search, surrounding context, no-match visibility and folded branch reveal');
const allRecords=new TreeModel(parser.detect('{"message":"before"}\n{"message":"needle"}\n{"message":"after"}'));
allRecords.configure({query:'needle'});
assert.deepEqual([...new Set(allRecords.rows.map(r=>allRecords.nodes[r.id].record))],[0,1,2]);
console.log('PASS searching JSONL preserves nonmatching records');
