const assert=require('node:assert/strict');
const {markdownTokens}=require('../markdown.js');
const {TreeModel}=require('../tree-model.js');
const parser=require('../parser.js');
const tokens=markdownTokens('**bold** and *italic* and `code`\n# Heading\n- item\n[link](https://example.com)');
assert(tokens.some(t=>t.type.includes('md-bold')&&t.text==='bold'));
assert(tokens.some(t=>t.type.includes('md-em')&&t.text==='italic'));
assert(tokens.some(t=>t.type.includes('md-code')&&t.text==='code'));
assert(tokens.some(t=>t.type.includes('md-heading')&&t.text==='Heading'));
assert(tokens.some(t=>t.href==='https://example.com'));
assert(!markdownTokens('[bad](javascript:alert(1))').some(t=>t.href));
assert.equal(markdownTokens('<img src=x onerror=alert(1)>').map(t=>t.text).join(''),'<img src=x onerror=alert(1)>');
console.log('PASS basic Markdown styles and text-only HTML handling');
const text=JSON.stringify({'**key**':'**bold**\nnext line','literal':'\\n','number':42});
const parsed=parser.detect(text),original=parser.serialize(parsed);
const m=new TreeModel(parsed,{wrap:false,markdown:true});
const value=m.rows.find(r=>r.tokens.some(t=>t.text==='bold'));
assert(value.tokens.some(t=>t.type==='key'&&t.text==='"**key**"'));
assert.equal(value.count,2);
assert(m.viewport(0,30).rows.some(r=>r.tokens.some(t=>t.text==='next line')));
assert.equal(parser.serialize(parsed),original);
m.configure({markdown:false});assert(m.rows.some(r=>r.tokens.some(t=>t.text==='"**bold**\\nnext line"')));
console.log('PASS values-only rendering, decoded newlines, toggle reversal and unchanged exports');
const big=new TreeModel(parser.detect(JSON.stringify({value:'**bold**\n'.repeat(20000)})),{markdown:true,wrap:true,columns:70});
assert(big.visualLines>20000);assert(big.viewport(10000,40).rows.length<=40);
console.log('PASS Markdown preview remains virtualized for large multiline values');
